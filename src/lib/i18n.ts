export type Language = keyof typeof translations;
export const supportedLanguages: Language[] = ['uz', 'en'];

export const languageLabels: Record<Language, string> = {
  uz: "O'zbek",
  en: 'English',
};

export type TranslationParams = Record<string, string | number>;

function getNestedValue(obj: Record<string, unknown>, key: string) {
  return key.split('.').reduce<unknown>((acc, part) => {
    if (!acc || typeof acc !== 'object') {
      return undefined;
    }

    return (acc as Record<string, unknown>)[part];
  }, obj);
}

function applyParams(value: string, params?: TranslationParams) {
  if (!params) return value;
  return Object.entries(params).reduce((result, [token, replacement]) => {
    return result.replace(new RegExp(`\\{${token}\\}`, 'g'), String(replacement));
  }, value);
}

export function getTranslation(
  language: Language,
  key: string,
  params?: TranslationParams,
  fallback?: string
) {
  const primary = getNestedValue(translations[language] as Record<string, unknown>, key);
  if (typeof primary === 'string') {
    return applyParams(primary, params);
  }

  const english = getNestedValue(translations.en as Record<string, unknown>, key);
  if (typeof english === 'string') {
    return applyParams(english, params);
  }

  return fallback ?? key;
}
